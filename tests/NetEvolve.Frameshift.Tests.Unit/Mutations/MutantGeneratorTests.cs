namespace NetEvolve.Frameshift.Tests.Unit.Mutations;

using Microsoft.CodeAnalysis;
using NetEvolve.Frameshift.Mutations;
using NetEvolve.Frameshift.Tests.Infrastructure;
using TUnit.Assertions;
using TUnit.Assertions.Extensions;
using TUnit.Core;

/// <summary>
/// Covers the single walk over a syntax tree: which operators are offered which nodes, and which whole
/// trees and declarations are dropped because they are machine written.
/// </summary>
public class MutantGeneratorTests
{
    private const string MixedSource = """
        public class Sample
        {
            public int Compute(int value, bool flag, string? text)
            {
                var sum = value + 1;
                var choice = flag ? sum : 0;
                var name = text ?? "fallback";

                return choice + name.Length;
            }
        }
        """;

    private const string AutoGeneratedSource = "// <auto-generated />\n" + MixedSource;

    private const string ExcludedSource = """
        public class Sample
        {
            [System.CodeDom.Compiler.GeneratedCode("tool", "1.0")]
            public int First(int value) => value + 1;

            [System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]
            public int Second(int value) => value + 2;
        }
        """;

    private const string IncludedSource = """
        public class Sample
        {
            public int First(int value) => value + 1;

            public int Second(int value) => value + 2;
        }
        """;

    [Test]
    public async Task CreateMutations_MixedSource_YieldsMutationsOfSeveralOperators()
    {
        var prefixes = Prefixes(Generate(MixedSource));

        _ = await Assert.That(prefixes).Contains("numeric-literal");
        _ = await Assert.That(prefixes).Contains("conditional-expression");
        _ = await Assert.That(prefixes).Contains("null-coalescing");
        _ = await Assert.That(prefixes).Contains("string-literal");
    }

    [Test]
    public async Task CreateMutations_MixedSource_YieldsWellFormedMutations()
    {
        var mutations = Generate(MixedSource);
        var span = RootOf(CompilationFactory.ParseTree(MixedSource)).FullSpan;
        var malformed = mutations
            .Where(mutation => !mutation.OperatorId.Contains('.', StringComparison.Ordinal))
            .Select(mutation => mutation.OperatorId);
        var unnamed = mutations.Where(mutation => mutation.DisplayName.Length == 0).Select(item => item.OperatorId);
        var outside = mutations
            .Where(mutation => !span.Contains(mutation.Location.SourceSpan))
            .Select(mutation => mutation.OperatorId);

        _ = await Assert.That(mutations.Length).IsGreaterThan(4);
        _ = await Assert.That(malformed).IsEmpty();
        _ = await Assert.That(unnamed).IsEmpty();
        _ = await Assert.That(outside).IsEmpty();
    }

    [Test]
    public async Task CreateMutations_GeneratedFileName_ReturnsEmpty()
    {
        var mutations = Generate(MixedSource, "Sample.g.cs");

        _ = await Assert.That(mutations).IsEmpty();
    }

    [Test]
    public async Task CreateMutations_DesignerFileName_ReturnsEmpty()
    {
        var mutations = Generate(MixedSource, "Sample.Designer.cs");

        _ = await Assert.That(mutations).IsEmpty();
    }

    [Test]
    public async Task CreateMutations_AutoGeneratedHeader_ReturnsEmpty()
    {
        var mutations = Generate(AutoGeneratedSource);

        _ = await Assert.That(mutations).IsEmpty();
    }

    [Test]
    public async Task CreateMutations_ExcludedMembers_ReturnsEmpty()
    {
        var mutations = Generate(ExcludedSource);

        _ = await Assert.That(mutations).IsEmpty();
    }

    [Test]
    public async Task CreateMutations_SameMembersWithoutExcludingAttributes_YieldsMutations()
    {
        var mutations = Generate(IncludedSource);

        _ = await Assert.That(mutations.Length).IsGreaterThan(0);
    }

    [Test]
    public async Task CreateMutations_EmptyFile_ReturnsEmpty()
    {
        var mutations = Generate(string.Empty);

        _ = await Assert.That(mutations).IsEmpty();
    }

    [Test]
    public async Task CreateMutations_CancelledToken_ThrowsOperationCanceledException()
    {
        var (_, semanticModel, tree) = CompilationFactory.CreateWithModel(MixedSource);
        var root = RootOf(tree);
        using var cancellation = new CancellationTokenSource();
        await cancellation.CancelAsync().ConfigureAwait(false);

        var exception = Assert.Throws<OperationCanceledException>(() =>
            _ = MutantGenerator.CreateMutations(root, semanticModel, cancellation.Token).ToList()
        );

        _ = await Assert.That(exception).IsNotNull();
    }

    [Test]
    public async Task CreateMutations_RootNull_ThrowsArgumentNullException()
    {
        var (_, semanticModel, _) = CompilationFactory.CreateWithModel(MixedSource);

        var exception = Assert.Throws<ArgumentNullException>(() =>
            MutantGenerator.CreateMutations(null!, semanticModel, CancellationToken.None)
        );

        _ = await Assert.That(exception.ParamName).IsEqualTo("root");
    }

    [Test]
    public async Task CreateMutations_SemanticModelNull_ThrowsArgumentNullException()
    {
        var (_, _, tree) = CompilationFactory.CreateWithModel(MixedSource);
        var root = RootOf(tree);

        var exception = Assert.Throws<ArgumentNullException>(() =>
            MutantGenerator.CreateMutations(root, null!, CancellationToken.None)
        );

        _ = await Assert.That(exception.ParamName).IsEqualTo("semanticModel");
    }

    [Test]
    public async Task CreateMutations_MixedSource_CompilesWithoutErrors()
    {
        var compilation = CompilationFactory.Create(MixedSource);

        _ = await Assert.That(CompilationFactory.GetCompileErrors(compilation).Length).IsEqualTo(0);
    }

    private static Mutation[] Generate(string source, string filePath = CompilationFactory.DefaultFilePath)
    {
        var (_, semanticModel, tree) = CompilationFactory.CreateWithModel(source, filePath: filePath);

        return [.. MutantGenerator.CreateMutations(tree.GetRoot(), semanticModel, CancellationToken.None)];
    }

    /// <summary>
    /// Reads the root of <paramref name="tree" /> outside an <see langword="async" /> method, which is
    /// where the synchronous accessor is the correct one.
    /// </summary>
    /// <param name="tree">The tree to read.</param>
    /// <returns>The root node.</returns>
    private static SyntaxNode RootOf(SyntaxTree tree) => tree.GetRoot();

    private static string[] Prefixes(Mutation[] mutations) =>
        [
            .. mutations
                .Select(mutation => mutation.OperatorId.Split('.')[0])
                .Distinct(StringComparer.Ordinal)
                .OrderBy(prefix => prefix, StringComparer.Ordinal),
        ];
}

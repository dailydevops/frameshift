    [Test]
    public async Task CreateMutations_MixedSource_YieldsWellFormedMutations()
    {
        var mutations = Generate(MixedSource);
        var span = RootOf(CompilationFactory.ParseTree(MixedSource)).FullSpan;
        var malformed = mutations
            .Where(mutation => !mutation.OperatorId.Contains('.', StringComparison.Ordinal))
            .Select(mutation => mutation.OperatorId);
        var unnamed = mutations.Where(mutation => mutation.DisplayName.Length == 0).Select(item => item.OperatorId);
        var outside = mutations
            .Where(mutation => !span.Contains(mutation.Location.SourceSpan))
            .Select(mutation => mutation.OperatorId);

        using (Assert.Multiple())
        {
            _ = await Assert.That(mutations.Length).IsGreaterThan(4);
            _ = await Assert.That(malformed).IsEmpty();
            _ = await Assert.That(unnamed).IsEmpty();
            _ = await Assert.That(outside).IsEmpty();
        }
    }


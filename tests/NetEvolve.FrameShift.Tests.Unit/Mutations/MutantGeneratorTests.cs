    /// <summary>
    /// The walk is lazy, so a token cancelled after the sequence was handed out still stops it. Nothing is
    /// produced, because the first thing the walk does for a node is observing the token.
    /// </summary>
    [Test]
    public async Task CreateMutations_CancelledAfterTheSequenceWasCreated_ThrowsBeforeYieldingAnything()
    {
        var (_, semanticModel, tree) = CompilationFactory.CreateWithModel(MixedSource);
        var root = RootOf(tree);
        using var cancellation = new CancellationTokenSource();
        var mutations = MutantGenerator.CreateMutations(root, semanticModel, cancellation.Token);
        var taken = new List<Mutation>();
        await cancellation.CancelAsyncCompat().ConfigureAwait(false);

        var exception = Assert.Throws<OperationCanceledException>(() =>
        {
            foreach (var mutation in mutations)
            {
                taken.Add(mutation);
            }
        });

        using (Assert.Multiple())
        {
            _ = await Assert.That(exception).IsNotNull();
            _ = await Assert.That(taken).IsEmpty();
        }
    }


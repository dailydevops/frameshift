    private static Mutation[] Generate(string source, string filePath = CompilationFactory.DefaultFilePath)
    {
        var (_, semanticModel, tree) = CompilationFactory.CreateWithModel(source, filePath: filePath);

        return [.. MutantGenerator.CreateMutations(tree.GetRoot(), semanticModel, CancellationToken.None)];
    }

    /// <summary>
    /// Walks <paramref name="source" /> through the overload taking the configuration.
    /// </summary>
    /// <param name="source">The fixture to walk.</param>
    /// <param name="options">The configuration deciding which operator families are asked.</param>
    /// <returns>The produced mutations, in the order the walk yields them.</returns>
    private static Mutation[] Generate(string source, FrameShiftOptions options)
    {
        var (_, semanticModel, tree) = CompilationFactory.CreateWithModel(source);

        return [.. MutantGenerator.CreateMutations(tree.GetRoot(), semanticModel, options, CancellationToken.None)];
    }

    /// <summary>
    /// Builds a configuration that differs from the defaults only in the pattern family switch. The
    /// constructor is private, so the value goes through the configuration reader.
    /// </summary>
    /// <param name="enableRegexPatternMutations">The value of the pattern family switch.</param>
    /// <returns>The created options.</returns>
    private static FrameShiftOptions Options(bool enableRegexPatternMutations)
    {
        var value = enableRegexPatternMutations ? "true" : "false";

        return FrameShiftOptions.Read(
            new TestAnalyzerConfigOptions(
                new Dictionary<string, string>(StringComparer.Ordinal)
                {
                    [FrameShiftOptionKeys.EnableRegexPatternMutations] = value,
                }
            )
        );
    }

    /// <summary>
    /// Names the operators that contributed a mutation, which is the full mutation identifier without its
    /// trailing suffix segment.
    /// </summary>
    /// <param name="mutations">The produced mutations.</param>
    /// <returns>The distinct operator identifiers, comma separated and ordered ordinally.</returns>
    private static string OperatorIds(Mutation[] mutations) =>
        string.Join(
            ", ",
            mutations
                .Select(mutation => mutation.OperatorId.Split('.'))
                .Select(segments => string.Join(".", segments.Take(segments.Length - 1)))
                .Distinct(StringComparer.Ordinal)
                .OrderBy(id => id, StringComparer.Ordinal)
        );

    /// <summary>
    /// Spells out every mutation as one line, so that two walks can be compared in a single assertion.
    /// </summary>
    /// <param name="mutations">The produced mutations.</param>
    /// <returns>The lines, in the order the walk yielded the mutations.</returns>
    private static string Describe(Mutation[] mutations) =>
        string.Join("\n", mutations.Select(mutation => mutation.OperatorId + " | " + mutation.DisplayName));

    /// <summary>
    /// Reads the source text every mutation of <paramref name="source" /> points at, which names the
    /// mutation points a fixture produced without depending on the operator ids behind them.
    /// </summary>
    /// <param name="source">The fixture to walk.</param>
    /// <returns>The distinct mutated snippets, ordered ordinally.</returns>
    private static string[] Snippets(string source) =>
        [
            .. Generate(source)
                .Select(mutation => mutation.Location.SourceSpan)
                .Select(span => source.Substring(span.Start, span.Length))
                .Distinct(StringComparer.Ordinal)
                .OrderBy(snippet => snippet, StringComparer.Ordinal),
        ];

    /// <summary>
    /// Reads the root of <paramref name="tree" /> outside an <see langword="async" /> method, which is
    /// where the synchronous accessor is the correct one.
    /// </summary>
    /// <param name="tree">The tree to read.</param>
    /// <returns>The root node.</returns>
    private static SyntaxNode RootOf(SyntaxTree tree) => tree.GetRoot();

    private static string[] Prefixes(Mutation[] mutations) =>
        [
            .. mutations
                .Select(mutation => mutation.OperatorId.Split('.')[0])
                .Distinct(StringComparer.Ordinal)
                .OrderBy(prefix => prefix, StringComparer.Ordinal),
        ];
}
